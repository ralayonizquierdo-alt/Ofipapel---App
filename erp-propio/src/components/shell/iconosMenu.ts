/** Pone el icono y el color de su menú a cada opción que no lo traiga ya (también en submenús). */
export function ponerIconos(menus: TopMenu[]) {
  const recorrer = (menu: string, entradas: MenuEntry[]) => {
    for (const e of entradas) {
      if (e === 'sep') continue
      const ic = ICONOS[`${menu}>${e.label}`] ?? ICONOS[e.label]
      if (!e.icono && ic) {
        const [icono, color] = Array.isArray(ic) ? ic : [ic, COLOR_MENU[menu] ?? '#1d3a8a']
        e.icono = icono
        e.colorIcono = color
      }
      if (e.children) recorrer(menu, e.children)
    }
  }
  for (const m of menus) recorrer(m.label, m.items)
}
