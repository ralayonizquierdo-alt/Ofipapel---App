-- Almacén → Control de Lotes calcado de GeminisWin (capturas ZIP 7, 04/11/2026).
-- En GeminisWin el lote es una FICHA: tienda, Id. Lote, nº de lote externo, descripción,
-- proveedor, artículo, códigos de barras (EAN*UCC-14, 1º y 2º EAN 128, SSCC), fechas de
-- consumo y datos de producción (trazabilidad), con dos rejillas: «Series o Sublotes» y
-- «Stock del Lote» (stock por serie y almacén que NO repercute en el stock general).
-- La tabla antigua articulo_lote (desglose con movimientos, usada por «Stock A 0 de Familia»
-- y «Elimina ArtiEnBlanco») no se toca.

create table if not exists public.lote (
  id bigint generated by default as identity primary key,
  tienda_terminal_codigo text references public.tienda_terminal(codigo),
  lote_externo text,
  descripcion text,
  proveedor_codigo text references public.proveedor(codigo),
  articulo_codigo text references public.articulo(codigo_interno),
  -- Códigos de barras
  ean_ucc14 text,
  ean128_1 text,
  ean128_2 text,
  sscc text,
  -- Fechas consumo
  fecha_entrada date,
  fecha_envasado date,
  fecha_consumo_preferente date,
  fecha_caducidad date,
  -- Datos de producción: características
  variedad text,
  clasificacion text,
  pieza text,
  conservacion text,
  -- Datos de producción: países, registros sanitarios y fechas
  pais_produccion_codigo text references public.pais(codigo),
  pais_nacimiento_codigo text references public.pais(codigo),
  pais_sacrificio_codigo text references public.pais(codigo),
  pais_despiece_codigo text references public.pais(codigo),
  pais_cebo_codigo text references public.pais(codigo),
  fecha_produccion date,
  fecha_nacimiento date,
  registro_sanitario_sacrificio text,
  fecha_sacrificio date,
  registro_sanitario_despiece text,
  fecha_envasado_despiece date,
  observaciones text,
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists lote_articulo_idx on public.lote (articulo_codigo);
create index if not exists lote_proveedor_idx on public.lote (proveedor_codigo);

create table if not exists public.lote_serie (
  id bigint generated by default as identity primary key,
  lote_id bigint not null references public.lote(id) on delete cascade,
  numero_serie text not null check (btrim(numero_serie) <> ''),
  fecha_entrada date,
  serie_secundaria text,
  serie_electronica text,
  creado_en timestamptz not null default now(),
  unique (lote_id, numero_serie)
);

create table if not exists public.lote_stock (
  id bigint generated by default as identity primary key,
  lote_id bigint not null references public.lote(id) on delete cascade,
  numero_serie text not null default '',
  almacen_codigo text not null references public.almacen(codigo),
  stock numeric(14,3) not null default 0,
  creado_en timestamptz not null default now(),
  unique (lote_id, numero_serie, almacen_codigo)
);

create or replace function public.fn_lote_actualizado_en()
returns trigger language plpgsql set search_path = public as $$
begin
  new.actualizado_en := now();
  return new;
end;
$$;
drop trigger if exists trg_lote_actualizado_en on public.lote;
create trigger trg_lote_actualizado_en before update on public.lote
  for each row execute function public.fn_lote_actualizado_en();

alter table public.lote enable row level security;
alter table public.lote_serie enable row level security;
alter table public.lote_stock enable row level security;

do $$
declare t text;
begin
  foreach t in array array['lote', 'lote_serie', 'lote_stock'] loop
    execute format('drop policy if exists %I on public.%I', t || '_lee', t);
    execute format('drop policy if exists %I on public.%I', t || '_alta', t);
    execute format('drop policy if exists %I on public.%I', t || '_modifica', t);
    execute format('drop policy if exists %I on public.%I', t || '_borra', t);
    execute format('create policy %I on public.%I for select to authenticated using (true)', t || '_lee', t);
    execute format('create policy %I on public.%I for insert to authenticated with check ((select public.fn_puede(''/almacen/lotes''))))', t || '_alta', t);
    execute format('create policy %I on public.%I for update to authenticated using ((select public.fn_puede(''/almacen/lotes''))) with check ((select public.fn_puede(''/almacen/lotes'')))', t || '_modifica', t);
    execute format('create policy %I on public.%I for delete to authenticated using ((select public.fn_puede(''/almacen/lotes'')))', t || '_borra', t);
    execute format('create or replace trigger %I after insert or update or delete on public.%I for each row execute function public.fn_auditoria_trigger()', 'trg_auditoria_' || t, t);
  end loop;
end $$;

grant select, insert, update, delete on public.lote, public.lote_serie, public.lote_stock to authenticated;
revoke all on public.lote, public.lote_serie, public.lote_stock from anon;
